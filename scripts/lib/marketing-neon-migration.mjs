/** Keep consent/transaction behavior identical to the original Postgres migration. */
export function neonMigration(source){
 if(!source.includes('create function public.marketing_subscribe')||!source.includes('grant usage on schema public to service_role;'))throw Error('unexpected_source_migration');
 const body=source.replaceAll('from public,anon,authenticated','from public').replaceAll('to service_role','to ceo19_marketing_runtime');
 if(/\b(?:anon|authenticated|service_role)\b/.test(body))throw Error('unconverted_supabase_role');
 return `-- Generated by scripts/generate-marketing-neon-migration.mjs. Fresh dedicated database only.
-- No account credentials or passwords belong in this migration.
create role ceo19_marketing_runtime nologin nosuperuser nocreatedb nocreaterole nobypassrls;
create role ceo19_waitlist_app login inherit nosuperuser nocreatedb nocreaterole nobypassrls;
grant ceo19_marketing_runtime to ceo19_waitlist_app;
revoke create on schema public from public;

${body}

-- No Supabase roles, Data API or RLS bypass role required.
create policy marketing_contacts_runtime on public.marketing_contacts for all to ceo19_marketing_runtime using(true) with check(true);
create policy marketing_rate_runtime on public.marketing_rate_limits for all to ceo19_marketing_runtime using(true) with check(true);
create policy marketing_versions_runtime on public.marketing_consent_versions for select to ceo19_marketing_runtime using(true);
create policy marketing_events_read on public.marketing_consent_events for select to ceo19_marketing_runtime using(true);
create policy marketing_events_append on public.marketing_consent_events for insert to ceo19_marketing_runtime with check(true);

create function public.marketing_runtime_allowed() returns boolean
language sql stable security invoker set search_path='' as $$
 select pg_catalog.pg_has_role(current_user,'ceo19_marketing_runtime','USAGE')
 and exists(select 1 from pg_catalog.pg_roles where rolname=current_user and not rolsuper and not rolbypassrls and not rolcreatedb and not rolcreaterole)
 and not exists(select 1 from pg_catalog.pg_roles where rolname='neon_superuser' and pg_catalog.pg_has_role(current_user,oid,'MEMBER'))
 and not exists(select 1 from pg_catalog.pg_class c join pg_catalog.pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relname='marketing_contacts' and c.relowner=current_user::regrole);
$$;
revoke all on function public.marketing_runtime_allowed() from public;
grant execute on function public.marketing_runtime_allowed() to ceo19_marketing_runtime;
`;
}

/** One atomic server-side statement, accepted by Neon's HTTP extended query transport. */
export function neonBootstrapStatement(migration,password){
 if(!/^[A-Za-z0-9_-]{43}$/.test(password))throw Error('invalid_generated_password');
 const sql=literal=>`'${literal.replaceAll("'","''")}'`;
 return `DO $ceo19_setup$ BEGIN
 PERFORM pg_catalog.pg_advisory_xact_lock(190019,5);
 IF pg_catalog.to_regclass('public.marketing_contacts') IS NOT NULL OR EXISTS(SELECT 1 FROM pg_catalog.pg_roles WHERE rolname IN ('ceo19_waitlist_app','ceo19_marketing_runtime')) THEN RAISE EXCEPTION 'marketing_setup_already_exists'; END IF;
 EXECUTE ${sql(migration)};
 EXECUTE ${sql(`ALTER ROLE ceo19_waitlist_app PASSWORD '${password}'`)};
 END $ceo19_setup$;`;
}
