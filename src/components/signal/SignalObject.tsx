'use client';
import { useEffect, useMemo, useRef, type RefObject } from 'react';
import { useFrame } from '@react-three/fiber';
import { Color, Group, PerspectiveCamera } from 'three';
import {channelWorlds} from '@/data/channelWorlds';
import {motion} from '@/lib/motion';
import { damp, mix } from './signalMath';
import { createSignalGeometry } from './signalGeometry';
import { createSignalMaterial } from './SignalMaterial';
import { signalConfig, resolveSignalState, type Quality } from './signalStates';
import type { SignalRuntime } from './useSignalScroll';
export interface Palette { blue: string; black: string; cream: string; silver: string; }
export function SignalObject({ runtime, quality, palette }: { runtime: RefObject<SignalRuntime>; quality: Quality; palette: Palette }) {
 const group = useRef<Group>(null);
 const geometry = useMemo(() => createSignalGeometry(quality),[quality]);
 const { material, uniforms, baseColor, chromeColor } = useMemo(() => createSignalMaterial(quality,palette,signalConfig.noise.strength,signalConfig.noise.speed),[quality,palette]);
 const colors=useMemo(()=>Object.fromEntries(Object.entries(channelWorlds).map(([id,world])=>[id,new Color(!world.accentColor||world.accentColor.startsWith('var(')?palette.blue:world.accentColor)])),[palette]);
 const channelLight=useMemo(()=>new Color(palette.blue),[palette]);
 const globalBlue=useMemo(()=>new Color(palette.blue),[palette]);
 const time = useRef(0);
 const initialized = useRef(false);
 const telemetry = useRef(0);
 const frameRate = useRef(60);
 useEffect(() => () => { geometry.dispose(); material.dispose(); },[geometry,material]);
 useFrame(({ camera, size, gl },rawDelta) => {
  if (!group.current) return;
  const dt = Math.min(rawDelta,.05);
  time.current += dt;
  const target = runtime.current;
  target.impulse=damp(target.impulse??0,0,motion.impulseDecay,dt);
  const response=1+(target.impulse??0)*.06;
  const a = resolveSignalState(target.from,target.channelId), b = resolveSignalState(target.to,target.channelId), t = target.progress;
  const transmissionWeight=mix(target.from==='music'?1:0,target.to==='music'?1:0,t);
  const energy=1+((target.transmissionEnergy??1)-1)*transmissionWeight;
  // Uniforms and transforms mutate in place. No geometry buffers, vectors or arrays allocated per frame.
  const speed = mix(signalConfig.morphSpeed,4600/motion.channels[channelWorlds[target.channelId??'']?.motionProfile??'press'],transmissionWeight);
  const smoothingDelta = initialized.current ? dt : 10;
  initialized.current = true;
  uniforms.uTime.value = time.current;
  uniforms.uDuality.value=damp(uniforms.uDuality.value,mix(a.duality,b.duality,t),speed,smoothingDelta);
  uniforms.uNoiseSpeed.value=damp(uniforms.uNoiseSpeed.value,mix(a.noiseSpeed,b.noiseSpeed,t),speed,smoothingDelta);
  channelLight.copy(globalBlue).lerp(colors[target.channelId??'']??globalBlue,transmissionWeight);
  uniforms.uBlue.value.lerp(channelLight,1-Math.exp(-speed*smoothingDelta));
  material.emissive.copy(uniforms.uBlue.value);
  uniforms.uArchitecture.value = damp(uniforms.uArchitecture.value,mix(a.architecture,b.architecture,t),speed,smoothingDelta);
  uniforms.uMorph.value = damp(uniforms.uMorph.value,mix(a.morph,b.morph,t),speed,smoothingDelta);
  uniforms.uLens.value = damp(uniforms.uLens.value,mix(a.lens,b.lens,t),speed,smoothingDelta);
  uniforms.uNoiseFrequency.value = damp(uniforms.uNoiseFrequency.value,mix(a.noiseFrequency,b.noiseFrequency,t),speed,smoothingDelta);
  uniforms.uNoiseAmplitude.value = damp(uniforms.uNoiseAmplitude.value,mix(a.noiseAmplitude,b.noiseAmplitude,t)*energy*response*(target.playing ? 1.13 : 1),speed,smoothingDelta);
  uniforms.uFrequency.value = damp(uniforms.uFrequency.value,mix(a.frequency,b.frequency,t)*(target.playing ? 1.1 : 1),speed,smoothingDelta);
  uniforms.uFragmentation.value = damp(uniforms.uFragmentation.value,mix(a.fragmentation,b.fragmentation,t),speed,smoothingDelta);
  uniforms.uWireframe.value = damp(uniforms.uWireframe.value,mix(a.wireframe,b.wireframe,t),speed,smoothingDelta);
  uniforms.uNodes.value = damp(uniforms.uNodes.value,mix(a.nodes,b.nodes,t),speed,smoothingDelta);
  material.emissiveIntensity = damp(material.emissiveIntensity,mix(a.emission,b.emission,t)*energy*response*(target.playing ? 1.08 : 1)*(target.hover ? 1.04 : 1),speed,smoothingDelta);
  material.color.copy(baseColor).lerp(chromeColor,mix(a.chrome,b.chrome,t));
  material.metalness = damp(material.metalness,mix(a.metalness,b.metalness,t),speed,smoothingDelta);
  material.roughness = damp(material.roughness,mix(a.roughness,b.roughness,t),speed,smoothingDelta);
  const mobile = quality === 'mobile';
  const cameraZ = mix(mobile ? a.mobileCamera : a.camera,mobile ? b.mobileCamera : b.camera,t)*signalConfig.cameraDistance;
  camera.position.z = damp(camera.position.z,cameraZ,speed,smoothingDelta);
  const strength = mobile ? 0 : signalConfig.pointerStrength;
  camera.position.x = damp(camera.position.x,target.pointerX*strength*.5,2,dt);
  camera.position.y = damp(camera.position.y,-target.pointerY*strength*.5,2,dt);
  const worldHeight = 2*Math.tan((camera as PerspectiveCamera).fov*Math.PI/360)*camera.position.z;
  const worldWidth = worldHeight*size.width/size.height;
  const scale = Math.min(target.width/size.width*worldWidth,target.height/size.height*worldHeight)/4 * mix(a.scale,b.scale,t);
  const object = group.current;
  object.scale.setScalar(damp(object.scale.x,scale,speed,smoothingDelta));
  object.position.x = damp(object.position.x,(target.x-.5)*worldWidth,speed,smoothingDelta);
  object.position.y = damp(object.position.y,(.5-target.y)*worldHeight,speed,smoothingDelta);
  object.rotation.x = damp(object.rotation.x,mix(a.rotation[0],b.rotation[0],t)+target.pointerY*strength,2.5,smoothingDelta);
  object.rotation.y = damp(object.rotation.y,mix(a.rotation[1],b.rotation[1],t)+target.pointerX*strength,2.5,smoothingDelta);
  object.rotation.z = damp(object.rotation.z,mix(a.rotation[2],b.rotation[2],t),2.5,smoothingDelta);
  if (rawDelta > 0 && rawDelta < 1) frameRate.current = mix(frameRate.current,1/rawDelta,.05);
  telemetry.current += dt;
  if (telemetry.current > .25) {
   telemetry.current = 0;
   gl.domElement.dataset.channel = target.channelId??'';
   gl.domElement.dataset.duality = uniforms.uDuality.value.toFixed(3);
   gl.domElement.dataset.morph = uniforms.uMorph.value.toFixed(3);
   gl.domElement.dataset.lens = uniforms.uLens.value.toFixed(3);
   gl.domElement.dataset.fragmentation = uniforms.uFragmentation.value.toFixed(3);
   gl.domElement.dataset.quality = quality;
   gl.domElement.dataset.fps = frameRate.current.toFixed(0);
   gl.domElement.dataset.playing = String(target.playing);
   gl.domElement.dataset.time = time.current.toFixed(2);
  }
 });
 return <group ref={group}><mesh geometry={geometry} material={material} frustumCulled={false} /></group>;
}
